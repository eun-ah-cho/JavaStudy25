package ex1;

public class StringExam11 {

	public static void main(String[] args) {
		int result = 0;
		result += 10 ; // result = result + 10 
		result -= 5; // result = result(10) - 5
		result *=3 ; // result = result(5)*3
		result /= 5; // result = result(15)/5
		result %= 3; // result = result(3)%3
	}

}
